/**
 * The exact clips of every written answer, as the app will ask for them.
 *
 * The natural voice is bought clip by clip from a tiny free allowance, and a
 * clip is only reused when its text matches to the character. So the server
 * pre-records the written answers overnight (vuka-server/src/voice.mjs,
 * startVoiceWarmer) from this list — produced by the app's OWN speech code
 * (toSentences, sayAs, packClips) and the app's own answers, so the two can
 * never drift apart. check-speech fails the build if the committed list is
 * stale.
 *
 * Run: node scripts/gen-voice-warm.mjs            (writes the list)
 *      node scripts/gen-voice-warm.mjs --check    (fails if it is out of date)
 */
import { build } from 'esbuild';
import { mkdtempSync, rmSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(root, '..', 'vuka-server', 'src', 'voice-warm.json');

/* The same figures the live server hands the app (/api/config). */
const MIN_WAGE = 30.23;
const AUTO_RELEASE_HOURS = 72;

export async function warmClips() {
  const dir = mkdtempSync(join(tmpdir(), 'warm-'));
  const bundle = async (entry, name) => {
    const f = join(dir, name);
    await build({ entryPoints: [join(root, entry)], outfile: f, bundle: true, format: 'esm', platform: 'neutral', target: 'es2022', logLevel: 'silent' });
    return import(pathToFileURL(f).href);
  };
  const M = await bundle('src/lib/msizi.ts', 'm.mjs');
  const D = await bundle('src/data/msizi.ts', 'd.mjs');
  const S = await bundle('src/lib/speech.ts', 's.mjs');
  rmSync(dir, { recursive: true, force: true });

  const ctx = (role) => ({
    role, name: '', cv: null, minWage: MIN_WAGE, autoReleaseHours: AUTO_RELEASE_HOURS,
    applied: 0, gigsNearby: 0, unread: 0, idVerified: false,
  });
  /* Most-asked first: the opening suggestions, then everything else. */
  const first = new Set([...D.OPENERS.worker, ...D.OPENERS.employer]);
  const entries = [...D.KNOWLEDGE].sort((a, b) => Number(first.has(b.id)) - Number(first.has(a.id)));

  const clips = [];
  const seen = new Set();
  for (const e of entries) {
    const reply = M.askById(e.id, ctx(e.role ?? 'worker'));
    if (!reply) continue;
    /* Exactly what readAloud hands speak(), then exactly what speak() sends. */
    const text = reply.title ? `${reply.title}.\n${reply.body}` : reply.body;
    const sentences = S.toSentences(text).map((s) => S.sayAs(s));
    for (const clip of S.packClips(sentences)) {
      const c = clip.replace(/\s+/g, ' ').trim();
      if (c && !seen.has(c)) { seen.add(c); clips.push(c); }
    }
  }
  return clips;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const clips = await warmClips();
  const next = `${JSON.stringify({ note: 'Generated by vuka-app/scripts/gen-voice-warm.mjs. Do not edit by hand.', clips }, null, 1)}\n`;
  if (process.argv.includes('--check')) {
    /* The deploy image builds the app in a stage that holds ONLY vuka-app, so
       the server's copy is not there to compare. That is not staleness — skip.
       CI builds from the whole repository and still enforces the check. */
    if (!existsSync(dirname(OUT))) {
      console.log('voice-warm check skipped: vuka-server is not in this build context (CI checks it).');
      process.exit(0);
    }
    /* Line endings are not content: a Windows checkout turns them into CRLF. */
    const current = existsSync(OUT) ? readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
    if (current !== next) {
      console.error('voice-warm.json is out of date: the written answers changed. Run: node scripts/gen-voice-warm.mjs');
      process.exit(1);
    }
    console.log(`voice-warm.json is current (${clips.length} clips)`);
  } else {
    writeFileSync(OUT, next);
    console.log(`wrote ${clips.length} clips to ${OUT}`);
  }
}
